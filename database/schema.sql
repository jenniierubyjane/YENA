CREATE TABLE IF NOT EXISTS clients (
 id CHAR(36) NOT NULL PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 institution VARCHAR(120) NOT NULL,
 contact VARCHAR(120) NOT NULL,
 need TEXT NOT NULL,
 stage VARCHAR(32) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS quotes (
 id CHAR(36) NOT NULL PRIMARY KEY,
 client_id CHAR(36) NULL,
 snapshot JSON NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT quotes_client_fk FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS client_accounts (
 client_id CHAR(36) NOT NULL PRIMARY KEY,
 email VARCHAR(120) NOT NULL UNIQUE,
 password_hash VARCHAR(160) NULL,
 invite_hash CHAR(64) NULL UNIQUE,
 invite_expires BIGINT NULL,
 webcam_enabled BOOLEAN NOT NULL DEFAULT FALSE,
 CONSTRAINT accounts_client_fk FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
